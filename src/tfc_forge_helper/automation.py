"""Opt-in, one-item forging with a single plan and verified completion.

Windows input is isolated behind a backend; tests use fake backends exclusively.
No input is generated by importing this module, discovery, or passive detection.
"""
import ctypes
import os
import threading
import time
from dataclasses import dataclass, replace

import numpy as np
from PIL import Image

from .coordinates import CoordinateError, DesktopLayout, Rect
from .engine import Config, Engine
from .model import Action
from .solver import solve
from .vision import DetectionError, Detector, Observation, distance


class AutomationStopped(ValueError):
    pass


@dataclass(frozen=True)
class Frame:
    image: Image.Image
    origin: tuple[int, int]
    pid: int
    window: int


@dataclass(frozen=True)
class RunResult:
    clicks: int
    message: str
    verified: bool


def state(observation: Observation):
    return observation.current, observation.target, observation.rules, tuple(a.category for a in observation.history)


class WindowsInput:
    """Only the foreground game window can receive clicks; no focus stealing."""
    def __init__(self, user=None, desktop: DesktopLayout | None = None):
        if os.name != "nt":
            raise AutomationStopped("自动打铁目前支持 Windows")
        from ctypes import wintypes
        self.wintypes = wintypes
        self.user = user if user is not None else ctypes.WinDLL("user32", use_last_error=True)
        self.desktop = desktop
        self.user.GetForegroundWindow.restype = wintypes.HWND
        self.user.GetWindowThreadProcessId.argtypes = [wintypes.HWND, ctypes.POINTER(wintypes.DWORD)]
        self.user.GetClientRect.argtypes = [wintypes.HWND, ctypes.POINTER(wintypes.RECT)]
        self.user.ClientToScreen.argtypes = [wintypes.HWND, ctypes.POINTER(wintypes.POINT)]
        self.user.WindowFromPoint.argtypes = [wintypes.POINT]
        self.user.WindowFromPoint.restype = wintypes.HWND

    def _window(self, pid):
        w = self.wintypes
        hwnd = self.user.GetForegroundWindow()
        actual = w.DWORD()
        self.user.GetWindowThreadProcessId(hwnd, ctypes.byref(actual))
        if not hwnd or actual.value != pid:
            raise AutomationStopped("游戏已失去焦点，自动打铁已停止")
        rectangle, point = w.RECT(), w.POINT(0, 0)
        if not self.user.GetClientRect(hwnd, ctypes.byref(rectangle)) or not self.user.ClientToScreen(hwnd, ctypes.byref(point)):
            raise AutomationStopped("无法确认游戏窗口位置，已停止")
        if rectangle.right < 176 or rectangle.bottom < 207:
            raise AutomationStopped("游戏窗口过小或已最小化，已停止")
        return hwnd, (point.x, point.y, rectangle.right, rectangle.bottom)

    def frame(self, pid) -> Frame:
        import mss
        hwnd, (x, y, w, h) = self._window(pid)
        with mss.MSS() as capture:
            shot = capture.grab({"left": x, "top": y, "width": w, "height": h})
            image = Image.frombytes("RGB", shot.size, shot.rgb)
        return Frame(image, (x, y), pid, hwnd)

    def move(self, frame: Frame, point: tuple[int, int], cancel: threading.Event):
        self.click(frame, point, point, cancel, move_only=True)

    def park(self, frame: Frame, cancel: threading.Event):
        try:
            layout = self.desktop or DesktopLayout.current(self.user)
            client = Rect(*frame.origin, frame.image.width, frame.image.height)
            point = layout.visible_park(client)
        except CoordinateError as exc:
            raise AutomationStopped(str(exc)) from exc
        self.move(frame, point, cancel)
        return point

    def click(self, frame: Frame, point: tuple[int, int], neutral: tuple[int, int], cancel: threading.Event,
              shift: bool = False, move_only: bool = False):
        w = self.wintypes
        hwnd, rectangle = self._window(frame.pid)
        if hwnd != frame.window or rectangle != (*frame.origin, frame.image.width, frame.image.height):
            raise AutomationStopped("游戏窗口在点击前移动或缩放，已停止")
        absolute = (frame.origin[0] + point[0], frame.origin[1] + point[1])
        try:
            layout = self.desktop or DesktopLayout.current(self.user)
            layout.normalize(*absolute)
            # Validate the post-click pointer position before any click, too.
            if not move_only:
                layout.normalize(frame.origin[0] + neutral[0], frame.origin[1] + neutral[1])
        except CoordinateError as exc:
            raise AutomationStopped(str(exc)) from exc
        target = self.user.WindowFromPoint(w.POINT(*absolute))
        target_pid = w.DWORD()
        self.user.GetWindowThreadProcessId(target, ctypes.byref(target_pid))
        if target_pid.value != frame.pid:
            raise AutomationStopped("按钮位置被其他窗口遮挡，已停止")

        class Mouse(ctypes.Structure):
            _fields_ = [("dx", w.LONG), ("dy", w.LONG), ("mouseData", w.DWORD),
                        ("dwFlags", w.DWORD), ("time", w.DWORD), ("dwExtraInfo", ctypes.c_size_t)]

        class Keyboard(ctypes.Structure):
            _fields_ = [("wVk", w.WORD), ("wScan", w.WORD), ("dwFlags", w.DWORD),
                        ("time", w.DWORD), ("dwExtraInfo", ctypes.c_size_t)]

        class Payload(ctypes.Union):
            _fields_ = [("mi", Mouse), ("ki", Keyboard)]

        class Input(ctypes.Structure):
            _fields_ = [("type", w.DWORD), ("payload", Payload)]

        self.user.SendInput.argtypes = [w.UINT, ctypes.POINTER(Input), ctypes.c_int]
        self.user.SendInput.restype = w.UINT

        def send(flags, x=0, y=0):
            event = Input(0, Payload(mi=Mouse(x, y, 0, flags, 0, 0)))
            if self.user.SendInput(1, ctypes.byref(event), ctypes.sizeof(Input)) != 1:
                raise AutomationStopped("Windows 未接受鼠标输入，已停止")

        def shift_key(release=False):
            event = Input(1, Payload(ki=Keyboard(0xA0, 0, 0x0002 if release else 0, 0, 0)))
            if self.user.SendInput(1, ctypes.byref(event), ctypes.sizeof(Input)) != 1:
                raise AutomationStopped("Windows 未接受 Shift 输入，已停止")

        def move(x, y):
            try:
                nx, ny = layout.normalize(x, y)
            except CoordinateError as exc:
                raise AutomationStopped(str(exc)) from exc
            send(0x0001 | 0x8000 | 0x4000, nx, ny)

        if cancel.is_set():
            raise AutomationStopped("自动打铁已停止")
        move(*absolute)
        if self._window(frame.pid) != (frame.window, (*frame.origin, frame.image.width, frame.image.height)):
            raise AutomationStopped("游戏窗口在点击前变化，已停止")
        if cancel.is_set():
            raise AutomationStopped("自动打铁已停止")
        if move_only:
            return
        if shift:
            shift_key()
        try:
            send(0x0002)
            try:
                cancel.wait(.04)
            finally:
                # Always release mouse and our Shift, including on cancellation.
                send(0x0004)
        finally:
            if shift:
                shift_key(release=True)
        if not cancel.is_set():
            self._window(frame.pid)
            move(frame.origin[0] + neutral[0], frame.origin[1] + neutral[1])


class AutoForge:
    def __init__(self, engine: Engine, backend=None, timeout=2.5, settle=.04, *, detector=None):
        self.engine = engine
        self.backend = backend
        self.timeout, self.settle = timeout, settle
        self._detector = detector
        self._detector_revision = engine.revision if detector is not None else None

    def run(self, config: Config, cancel: threading.Event, notify=lambda value: None,
            tolerance: int = 0, countdown: int = 3, completion_check=None, initial_frame=None) -> RunResult:
        backend = self.backend or WindowsInput()
        refresh = getattr(self.engine, "refresh_automation", self.engine.refresh)
        for remaining in range(countdown, 0, -1):
            notify(f"{remaining} 秒后开始，请切回游戏砧界面；F9 停止")
            if cancel.wait(1):
                raise AutomationStopped("自动打铁已取消")
        atlas, profile = refresh(config) if initial_frame is not None else self.engine.refresh(config)
        pid, revision = self.engine.pid, self.engine.revision
        if pid is None:
            raise AutomationStopped("未能从进程定位到当前实例，不能自动点击；请先启动游戏并完成实例检测")
        # Automation uses stricter matching than passive assistance.
        profile = replace(profile, threshold=max(.985, profile.threshold), margin=max(.004, profile.margin))
        if (self._detector is None or self._detector_revision != revision or
                self._detector.atlas is not atlas.image or self._detector.profile != profile):
            self._detector = Detector(atlas, profile)
            self._detector_revision = revision
        detector = self._detector
        frame = initial_frame if initial_frame is not None else backend.frame(pid)
        if frame.pid != pid:
            raise AutomationStopped("已确认画面不属于当前游戏进程，自动打铁已停止")
        observation = detector.detect(frame.image)
        solution = solve(observation.current, observation.target, observation.rules,
                         observation.history, tolerance=tolerance)
        if not solution.actions:
            return RunResult(0, "目标位置与规则均已满足，自动打铁已停止", True)
        if solution.steps > 64:
            raise AutomationStopped("方案超过本次操作上限，自动打铁未启动")
        gx, gy, gw, gh = observation.region
        gui = frame.image.crop((gx, gy, gx + gw, gy + gh)).resize(
            (profile.gui_width, profile.gui_height), Image.Resampling.NEAREST)
        # Validate every required button before starting the sequence.
        for action in set(solution.actions):
            bx, by = profile.buttons[list(Action).index(action)]
            expected_button = atlas.image.crop((bx, by, bx + 16, by + 16))
            expected_button.alpha_composite(atlas.image.crop((action.icon_x, 240, action.icon_x + 16, 256)))
            actual_button = gui.crop((bx, by, bx + 16, by + 16)).convert("RGB")
            if distance(np.array(actual_button), np.array(expected_button.convert("RGB"))) > .015:
                raise AutomationStopped("动作按钮与当前材质模板不符，已停止")
        sx, sy = gw / profile.gui_width, gh / profile.gui_height
        neutral = (round(gx + (profile.gui_width - 6) * sx), round(gy + 8 * sy))
        history = tuple(a.category for a in observation.history)
        expected_states = {state(observation)}
        for action, work in zip(solution.actions, solution.positions[1:]):
            history = (history + (action.category,))[-3:]
            expected_states.add((work, observation.target, observation.rules, history))
        expected_history = history
        clicks = 0
        for action in solution.actions:
            if cancel.is_set():
                raise AutomationStopped("自动打铁已停止")
            refresh(config)
            if self.engine.pid != pid or self.engine.revision != revision:
                raise AutomationStopped("实例或资源包发生变化，自动打铁已停止")
            bx, by = profile.buttons[list(Action).index(action)]
            point = (round(gx + (bx + 8) * sx), round(gy + (by + 8) * sy))
            notify(f"第 {clicks + 1}/{solution.steps} 步：{action.label} {action.delta:+d}")
            # Native input still validates foreground, geometry and occlusion
            # before each click. It never activates or moves the game window.
            backend.click(frame, point, neutral, cancel)
            clicks += 1
            if cancel.wait(self.settle):
                raise AutomationStopped("自动打铁已停止")
        notify(f"本件 {clicks} 步已发送，正在确认结果")
        deadline = time.monotonic() + self.timeout
        while time.monotonic() < deadline:
            if cancel.is_set():
                raise AutomationStopped("自动打铁已停止")
            refresh(config)
            if self.engine.pid != pid or self.engine.revision != revision:
                raise AutomationStopped("实例或资源包发生变化，自动打铁已停止")
            after_frame = backend.frame(pid)
            if completion_check is not None and completion_check(after_frame):
                return RunResult(clicks, "成品图标已确认", True)
            try:
                after = detector.detect(after_frame.image)
            except DetectionError as exc:
                # Completion often replaces the item and removes its pointers.
                try:
                    detector.locate(after_frame.image)
                except DetectionError:
                    raise AutomationStopped("最后一步后砧界面消失，已停止；请检查游戏") from exc
                return RunResult(clicks, "本件序列已发送，配方状态已变化；已停止，请核对成品", False)
            if after.target != observation.target or after.rules != observation.rules:
                raise AutomationStopped("配方已变化，自动打铁已停止")
            if (after.current == solution.positions[-1] and
                    tuple(a.category for a in after.history) == expected_history):
                return RunResult(clicks, "本件序列执行完成，目标位置与规则已确认", True)
            if state(after) not in expected_states:
                raise AutomationStopped("操作结果与预期不符，已停止；请检查进度与历史")
            # Slow frames/servers may still be showing a prefix of the sequence.
            # Wait for completion without resending any action.
            if cancel.wait(.02):
                raise AutomationStopped("自动打铁已停止")
        raise AutomationStopped("本件结果未能确认，已停止；请检查坯料温度、锤子或网络，不会重复发送序列")
